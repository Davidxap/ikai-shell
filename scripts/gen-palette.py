#!/usr/bin/env python3
"""Generate colors.toml and shell.toml from palette.toml.

The Ito-verse red used to be hand-written in three files that disagreed
(#a83859 in colors.toml, #ff2b4d in shell.toml, #6d1d1d in the QML modules).
This generator makes palette.toml the only place a color is ever chosen.

Every generated stop is contrast-checked against the ink background before it
is written, so a stop can never silently land in a role it cannot carry:

    paint stops fill shapes      - no contrast floor
    ui stops draw borders        - >= 3.0:1  (WCAG non-text)
    text stops carry glyphs      - >= 4.5:1  (WCAG normal text)

Usage:
    gen-palette.py --check          validate only, write nothing
    gen-palette.py --out DIR        generate into DIR (default: theme dir)
"""

import argparse
import colorsys
import sys
import tomllib
from pathlib import Path

THEME_DIR = Path(__file__).resolve().parent.parent / "themes" / "ito-verse"

# Minimum contrast each ramp stop must reach against the ink background.
CONTRAST_FLOOR = {
    "deep": None,
    "paint": None,
    "ui": 3.0,
    "focus": 3.0,
    "text": 4.5,
    "bright": 4.5,
}


def _linear(channel: int) -> float:
    c = channel / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _linear(r) + 0.7152 * _linear(g) + 0.0722 * _linear(b)


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def hue_of(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)[0]


def load(path: Path) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def validate(palette: dict) -> list[str]:
    """Return a list of problems. Empty list means the palette is sound."""
    problems = []
    ink = palette["base"]["ink"]
    blood = palette["blood"]

    if blood["paint"].lower() != blood["base"].lower():
        problems.append(
            f"blood.paint ({blood['paint']}) must equal blood.base ({blood['base']}): "
            "the anchor is the paint stop"
        )

    base_hue = hue_of(blood["base"])
    for stop, floor in CONTRAST_FLOOR.items():
        color = blood[stop]
        ratio = contrast(color, ink)

        # One hue for the whole ramp, or it stops reading as one family.
        drift = abs(hue_of(color) - base_hue) * 360
        drift = min(drift, 360 - drift)
        if drift > 6.0:
            problems.append(
                f"blood.{stop} ({color}) drifts {drift:.1f} deg from the base hue (max 6)"
            )

        if floor is not None and ratio < floor:
            problems.append(
                f"blood.{stop} ({color}) is {ratio:.2f}:1 on ink, needs >= {floor}:1"
            )
    return problems


def report(palette: dict) -> None:
    ink, bone = palette["base"]["ink"], palette["base"]["bone"]
    print(f"ink {ink}   bone {bone}   ({contrast(bone, ink):.2f}:1)\n")
    print(f"{'stop':<8}{'hex':<10}{'on ink':>9}{'bone on it':>13}   role floor")
    print("-" * 56)
    for stop, floor in CONTRAST_FLOOR.items():
        color = palette["blood"][stop]
        need = "paint (none)" if floor is None else f">= {floor}:1"
        print(
            f"{stop:<8}{color:<10}{contrast(color, ink):>8.2f}:1"
            f"{contrast(bone, color):>12.2f}:1   {need}"
        )


