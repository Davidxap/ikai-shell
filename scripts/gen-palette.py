def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    ap.add_argument("--out", type=Path, default=THEME_DIR, help="output directory")
    args = ap.parse_args()

    palette = load(THEME_DIR / "palette.toml")
    report(palette)

    problems = validate(palette)
    if problems:
        print("\nFAIL")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print("\nOK: every stop clears its role floor and holds the base hue.")

    if args.check:
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in (
        ("colors.toml", render_colors_toml(palette)),
        ("shell.toml", render_shell_toml(palette)),
    ):
        target = args.out / name
        tmp = target.with_suffix(target.suffix + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        assert tmp.read_text(encoding="utf-8") == text, f"readback mismatch for {name}"
        tmp.replace(target)
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
