class Canvas:
    """two layers (ink = bone token, blood = blood token), drawn at SS x the target, alpha 0..1."""
    def __init__(s, px, SS=8):
        s.px, s.SS = px, SS; s.S = px * SS; s.u = SS
        s.L = {k: Image.new("L", (s.S, s.S), 0) for k in ("ink", "blood")}
        s.D = {k: ImageDraw.Draw(v) for k, v in s.L.items()}

    # coordinates in target px (float); 0..px
    def P(s, x, y): return (x * s.u, y * s.u)

    def poly(s, pts, layer="ink", v=255):
        s.D[layer].polygon([s.P(x, y) for x, y in pts], fill=v)

    def disc(s, cx, cy, r, layer="ink", v=255):
        s.D[layer].ellipse((s.u * (cx - r), s.u * (cy - r), s.u * (cx + r), s.u * (cy + r)), fill=v)

    def ring(s, cx, cy, r, w, layer="ink", v=255):
        s.D[layer].ellipse((s.u * (cx - r - w / 2), s.u * (cy - r - w / 2), s.u * (cx + r + w / 2), s.u * (cy + r + w / 2)),
                           outline=v, width=max(1, int(round(w * s.u))))

    def stroke(s, pts, widths, layer="ink", v=255):
        """variable-width polyline as a chain of quads + round joints."""
        d = s.D[layer]
        for i in range(len(pts) - 1):
            (x0, y0), (x1, y1) = pts[i], pts[i + 1]
            w0, w1 = widths[i] / 2, widths[i + 1] / 2
            dx, dy = x1 - x0, y1 - y0; L = math.hypot(dx, dy) or 1e-6
            nx, ny = -dy / L, dx / L
            q = [(x0 + nx * w0, y0 + ny * w0), (x1 + nx * w1, y1 + ny * w1), (x1 - nx * w1, y1 - ny * w1), (x0 - nx * w0, y0 - ny * w0)]
            d.polygon([s.P(*p) for p in q], fill=v)
            if w1 > 0.05: s.disc(x1, y1, w1, layer, v)

    def erase(s, mask_img, layers=("ink", "blood")):
        from PIL import ImageChops
        for k in layers:
            s.L[k] = ImageChops.subtract(s.L[k], mask_img); s.D[k] = ImageDraw.Draw(s.L[k])

    def scratch(s):
        m = Image.new("L", (s.S, s.S), 0); return m, ImageDraw.Draw(m)

    def text(s, cx, cy, txt, size, font, layer="ink", v=255, stroke=0):
        f = ImageFont.truetype(font, int(size * s.u))
        d = s.D[layer]
        bb = d.textbbox((0, 0), txt, font=f, stroke_width=int(stroke * s.u))
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        d.text((cx * s.u - w / 2 - bb[0], cy * s.u - h / 2 - bb[1]), txt, font=f, fill=v, stroke_width=int(stroke * s.u), stroke_fill=v)

    def image(s, ink_alpha=1.0):
        """RGBA at the target size: ink = (200,200,200), blood = (200,16,20) (the recipe convention)."""
        a = np.asarray(s.L["ink"], np.float32) / 255 * ink_alpha
        b = np.asarray(s.L["blood"], np.float32) / 255
        a = a * (1 - b)
        return to_rgba(a, b, s.px)


def to_rgba(a, b, px=None):
    h, w = a.shape
    o = np.zeros((h, w, 4), np.float32)
    al = np.clip(a + b, 0, 1)
    o[..., 3] = al
    # premultiplied mix of ink grey and blood
    with np.errstate(invalid="ignore", divide="ignore"):
        fb = np.where(al > 0, b / np.maximum(al, 1e-6), 0)
    o[..., 0] = (INK * (1 - fb) + 200 * fb) / 255
    o[..., 1] = (INK * (1 - fb) + 16 * fb) / 255
    o[..., 2] = (INK * (1 - fb) + 20 * fb) / 255
    img = Image.fromarray((np.clip(o, 0, 1) * 255).astype(np.uint8), "RGBA")
    if px and img.width != px:
        img = img.convert("RGBa").resize((px, px), Image.LANCZOS).convert("RGBA")
    return img


