# ---- S2c-5: the Uzumaki menu mark below 64 px (port of lab v8 uzu_mark.py) --------------------------------------------------------
# v7 looked bad at x1 because the bone/blood gap was 1.0 px (a grey seam after antialiasing: the two arms fuse), the inner turn ran at
# r < 3 px with w0 1.3 (a smeared knot) and the outer cap touched the edge. Below 64 px: w0 >= 1.6, w1 >= 2.2, gap 1.5, an open centre
# (r0 >= 2.2), the outer edge 1 px inside, fewer turns (never more than 3) and a rotation hint of +-20 deg by crisp - 2 x seam.
# 64 px and up = the v7 mark unchanged. The workspace sets are untouched.
UZU_MICRO = dict(w0=1.6, w1=2.2, G=1.5, r0=2.2, margin=1.0, hint=20)


def umark_geom(px, P=UZU_MICRO):
    s = px / 512; R = px / 2
    w0 = max(P["w0"], 13 * s); w1 = max(P["w1"], 24 * s)
    r1 = min(226 * s, R - P["margin"] - w1 / 2)
    r0 = max(P["r0"], 20 * s)
    turns = min(3.0, (r1 - r0) / (2 * (w1 + P["G"])))
    return dict(r0=r0, r1=r1, w0=w0, w1=w1, turns=turns, phase0=(3.0 - turns) * OTAU)


def umark_draw(px, g, rot=0.0):
    c = px / 2; items = []; covs = []
    for ph, col in ((0.0, OBONE), (math.pi, OBLOOD)):
        L = OLayer(px); oribbon(L, c, g["r0"], g["r1"], g["turns"], g["w0"], g["w1"], ph + g["phase0"] + rot, caps=True)
        items.append((L.cov(), col, 1)); covs.append(items[-1][0])
    return ocomp(items, px), covs


def umark_score(covs):
    a, b = covs; tot = np.clip(a + b, 0, 1)
    crisp_ = (tot >= 0.6).sum() / max(1, (tot >= 0.15).sum())
    seam = ((a > 0.15) & (b > 0.15)).sum() / max(1, (tot > 0.15).sum())
    return crisp_ - 2 * seam


def mark_original(px):
    if px >= 64:
        return omark(px)[0]
    g = umark_geom(px); best = None
    for deg in range(-UZU_MICRO["hint"], UZU_MICRO["hint"] + 1):
        im, covs = umark_draw(px, g, math.radians(deg)); sc = umark_score(covs)
        if best is None or sc > best[0] + 1e-4: best = (sc, im)
    return best[1]


