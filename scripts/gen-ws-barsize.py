def crisp(im):
    al = np.asarray(im, np.float32)[..., 3] / 255.0
    mx = al.max() or 1
    return (al >= 0.6 * mx).sum() / max(1, (al >= 0.15 * mx).sum())


def ws_vnum_shipped(n, st, px):
    """Numbered variant for the bar: the empty state is the faintest and thinnest, so its stroke grows
    (+0.3 px per step, in units of the 28 px grid) until crisp >= 0.45."""
    if st != "empty":
        return ws_vnum(n, st, px)
    grow = 0.0
    while True:
        im = ws_vnum(n, st, px, grow)
        if crisp(im) >= 0.45 or grow >= 1.5:
            return im
        grow += 0.3


# ---- uzumaki-classic: the classic ORIGINAL drawing (gen-marks.py uzumaki_state: arm-count spiral, dashed outer ring for 6-10), -------
# pre-rendered per bucket. The six sizes the S1b fit shipped (40 44 56 64 80 88) are the exact S1b files, kept in
# scripts/data/classic-s1b/<px>/; the other sizes are rendered the same way (rsvg at 512, area filter down).
CLASSIC_SEED = os.path.join(HERE, "data", "classic-s1b")


@functools.lru_cache(maxsize=None)
def _gen_marks():
    sp = importlib.util.spec_from_file_location("gen_marks", os.path.join(HERE, "gen-marks.py"))
    m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); return m


def _classic_render(n, st, px, floor):
    """the classic svg at 512, every stroke widened to at least `floor` device px (the fit), area-filtered down to px."""
    import re
    svg = _gen_marks().uzumaki_state(n, st)
    k = px / 512.0
    if floor:
        def fat(m):                                         # a ribbon polygon: round-joined outline adds the missing width
            fill = m.group(2)
            w0 = {"empty": 7 * 0.7, "occupied": 7}.get(st, 7)
            return f'<polygon points="{m.group(1)}" fill="{fill}" stroke="{fill}" stroke-linejoin="round" stroke-width="{max(0.0, floor - w0 * k) / k:.2f}"'
        svg = re.sub(r'<polygon points="([^"]*)" fill="([^"]*)"', fat, svg)
        svg = re.sub(r'stroke-width="(\d+)"', lambda m: f'stroke-width="{max(int(m.group(1)), floor / k):.2f}"', svg)
    with tempfile.TemporaryDirectory() as t:
        src, big = os.path.join(t, "a.svg"), os.path.join(t, "a.png")
        open(src, "w").write(svg)
        subprocess.run(["rsvg-convert", "-w", "512", "-h", "512", src, "-o", big], check=True)
        return Image.open(big).convert("RGBA").resize((px, px), Image.BOX)


@functools.lru_cache(maxsize=None)
def _classic_floor(px):
    """the stroke floor (device px) for a bucket the S1b fit never shipped: the thickest floor whose 40-image set stays open
    (fill <= 0.52, the gate says 0.55), stopping once it is crisp (>= 0.47, the gate says 0.45). At 24-36 and 48 px the original's
    arm count cannot be both: crisp stays under the gate there and is report-only for this family (test-barsize-legibility.py)."""
    best = 0.0
    for f in [0.0] + [round(1.0 + 0.1 * i, 1) for i in range(0, 25)]:
        ims = [_classic_render(n, st, px, f) for n in range(1, 11) for st in STATES]
        if max(metrics(i)["fill"] for i in ims) > 0.52:
            break
        best = f
        if min(crisp(i) for i in ims) >= 0.47:
            break
    return best


def ws_classic(n, st, px):
    seed = os.path.join(CLASSIC_SEED, str(px), f"ws-uzumaki-classic-{n}-{st}.png")
    if os.path.exists(seed):
        return Image.open(seed).convert("RGBA")
    return _classic_render(n, st, px, _classic_floor(px))


